#[test]
fn parse_errors() {
    let err = |text: &str| yosys::parse(text).unwrap_err();
    let no_top = SAMPLE.replace("; yosys-smt2-topmod top\n", "");
    assert!(err(&no_top).contains("topmod"), "{}", err(&no_top));
    let two = format!("; yosys-smt2-module sub\n{SAMPLE}");
    assert!(
        err(&two).contains("expected only module `top`"),
        "{}",
        err(&two)
    );
    // malformed comments: no width, a width that is no number
    for line in ["; yosys-smt2-wire y\n", "; yosys-smt2-output y eight\n"] {
        let text = format!("{SAMPLE}{line}");
        assert_eq!(
            err(&text),
            format!("malformed Yosys comment: {}", line.trim_end())
        );
    }
    // the initial-state predicate missing, cut short, or with a line
    // that is no assertion of a sample's value
    let no_init = SAMPLE.replace("(define-fun |top_i|", "(define-fun |top_j|");
    assert_eq!(err(&no_init), "no `top_i` in the Yosys output");
    let cut = &SAMPLE[..SAMPLE.find("\n))\n").unwrap() + 1];
    let cut = format!("; yosys-smt2-topmod top\n{cut}");
    assert_eq!(err(&cut), "`top_i` does not end in the Yosys output");
    let odd = SAMPLE.replace(" ; $auto$clk2fflogic.cc:101:sample_data$/u.q#sampled$7", "");
    assert!(
        err(&odd).starts_with("unexpected Yosys line: "),
        "{}",
        err(&odd)
    );
    let widths = format!("{SAMPLE}; yosys-smt2-wire y 4\n");
    assert!(
        err(&widths).contains("`y` with widths 8 and 4"),
        "{}",
        err(&widths)
    );
    // inputs Yosys's predicates constrain
    let driven = "Yosys's input `a b` is not free in every step";
    for (from, to) in [
        // defined, not declared
        (
            "(declare-fun |top#3| (|top_s|) Bool)",
            "(define-fun |top#3| ((state |top_s|)) Bool true)",
        ),
        // a register
        (
            "\n))\n",
            "\n))\n(define-fun |top_t| ((state |top_s|) (next_state |top_s|)) Bool (|top#3| next_state))\n",
        ),
        // computed from a symbol
        ("Bool (|top#3| state))", "Bool (not (|top#3| state)))"),
        // a bit used twice
        (
            "Bool (|top#3| state))",
            "Bool (= (concat (|top#3| state) (|top#3| state)) #b11))",
        ),
        // no accessor
        ("(define-fun |top_n a b|", "(define-fun |top_n a c|"),
    ] {
        assert!(SAMPLE.contains(from), "{from}");
        let text = SAMPLE.replace(from, to);
        assert!(err(&text).starts_with(driven), "{}", err(&text));
    }
    let two = SAMPLE.replace(
        "; yosys-smt2-output y 8\n",
        "; yosys-smt2-input c 1\n(define-fun |top_n c| ((state |top_s|)) Bool (|top#3| state))\n",
    );
    assert!(
        err(&two).starts_with("Yosys's input `c` is not free in every step"),
        "{}",
        err(&two)
    );
    let anyseq = format!("{SAMPLE}; yosys-smt2-anyseq top#9 1 $cut\n");
    assert!(
        err(&anyseq).starts_with("Yosys's fresh value `top#9` is not a declared symbol of its own"),
        "{}",
        err(&anyseq)
    );
    // an input sharing its symbol with a fresh value
    let shared = format!("{SAMPLE}; yosys-smt2-anyseq top#3 1 $cut\n");
    assert!(err(&shared).starts_with(driven), "{}", err(&shared));
    // names that cannot be SMT-LIB quoted symbols (from an escaped
    // identifier or a source path in an internal name)
    for bad in [
        format!("{SAMPLE}; yosys-smt2-wire a|b 1\n"),
        format!("{SAMPLE}; yosys-smt2-register $x$/p|q.sv:1$2 1\n"),
        format!("{SAMPLE}; yosys-smt2-wire a\\b 1\n"),
        SAMPLE.replace("; yosys-smt2-topmod top\n", "; yosys-smt2-topmod t|p\n"),
    ] {
        assert!(
            err(&bad).contains("which an SMT-LIB symbol cannot"),
            "{}",
            err(&bad)
        );
    }
    let malformed = format!("{SAMPLE}; yosys-smt2-wire y\n");
    assert!(err(&malformed).contains("malformed"), "{}", err(&malformed));
    let (head, _) = SAMPLE.split_once("(define-fun |top_i|").unwrap();
    let no_init = format!("{head}; yosys-smt2-topmod top\n");
    assert!(err(&no_init).contains("no `top_i`"), "{}", err(&no_init));
    let open = SAMPLE.replace("\n))\n", "\n");
    assert!(
        err(&open).contains("unexpected Yosys line"),
        "{}",
        err(&open)
    );
    let open = SAMPLE.split_once("\n))\n").unwrap().0;
    assert!(err(open).contains("topmod"), "{}", err(open));
    let open = format!("{open}\n; yosys-smt2-topmod top\n");
    let open = open.replace("  (= (bvand", "; yosys-smt2-topmod top\n  (= (bvand");
    assert!(
        err(&open).contains("unexpected Yosys line"),
        "{}",
        err(&open)
    );
}

