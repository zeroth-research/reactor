/// Yosys's registers are three samples per register path of ours (four with
/// an asynchronous reset), its inputs and outputs are the top ports (clocks
/// and unread inputs included; pins are both), and every variable of our module except
/// `q@init` is a Yosys wire of the same width. With z3,
/// every accessor of [`yosys::Smt2::value`] is a bit vector of the listed
/// width, and the transition and hierarchy predicates are satisfiable.
#[test]
fn names_match_examples() {
    let Some(bin) = yosys::find() else {
        common::missing("yosys", "the whole test");
        return;
    };
    let z3 = z3::find();
    if z3.is_none() {
        common::missing("z3", "the check of the accessor sorts");
    }
    for path in examples() {
        let (inst, t) = load(&path);
        let ys = yosys::run(&bin, &[&path], &t.name, &[])
            .unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        let at = |what| format!("{}: {what}", path.display());
        assert_eq!(ys.top, t.name, "{}", at("top"));
        assert_eq!(
            ys.registers.len(),
            3 * common::registers(&inst).len() + t.reset_registers.len(),
            "{}",
            at("registers (three per register, one more with an asynchronous reset)")
        );
        assert_eq!(ys.inputs, ports(&inst, Dir::Input), "{}", at("inputs"));
        assert_eq!(ys.outputs, ports(&inst, Dir::Output), "{}", at("outputs"));
        for (name, var) in &t.vars {
            if name.ends_with("@init") {
                continue;
            }
            let width = var.dtype().width();
            assert_eq!(ys.wires.get(name), Some(&width), "{}", at(name));
        }
        if let Some(z3) = &z3 {
            let mut script = ys.text.clone();
            script += &format!("(declare-const s {})\n", ys.state_sort());
            script += &format!("(declare-const t {})\n", ys.state_sort());
            script += &format!("(assert {})\n", ys.hierarchy("s"));
            script += &format!("(assert {})\n", ys.transition("s", "t"));
            for (i, (name, w)) in ys.wires.iter().enumerate() {
                let v = ys.value(name, "s").unwrap();
                script += &format!("(declare-const w{i} (_ BitVec {w}))\n(assert (= w{i} {v}))\n");
            }
            script += "(check-sat)\n";
            let out = z3::run(z3, &script).unwrap();
            assert_eq!(out, ["sat"], "{}", at("accessor sorts"));
        }
    }
}

/// The miter of an example, from Yosys's translation of it.
fn miter_of(yosys: &Path, path: &Path) -> (Translation, yosys::Smt2, miter::Miter) {
    let (_, t) = load(path);
    let ys = yosys::run(yosys, &[path], &t.name, &[])
        .unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let m = miter::build(&t, &ys).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    (t, ys, m)
}

/// On every example, our init round and Yosys's state, and one round of
/// our module and one transition of Yosys's, agree on every controlled
/// variable, and every one is queried in both rounds.
#[test]
fn miter_examples() {
    let Some((yosys, z3)) = tools() else { return };
    for path in examples() {
        let (t, _, m) = miter_of(&yosys, &path);
        let mut controlled: Vec<&str> = t.module.ctrl().iter().map(|v| t.name(v)).collect();
        controlled.sort();
        for phase in [Phase::Init, Phase::Update] {
            let queries = m.queries.iter().filter(|q| q.phase == phase);
            let mut queried: Vec<&str> = queries.map(|q| q.name.as_str()).collect();
            queried.sort();
            assert_eq!(queried, controlled, "{}: {phase:?}", path.display());
        }
        for (phase, name, verdict) in miter::check(&z3, &m).unwrap() {
            let at = format!("{}: `{name}` in {phase:?}", path.display());
            assert_eq!(verdict, Verdict::Equal, "{at}");
        }
    }
}

/// Designs on which Yosys's defaults would give SMT the miter cannot use:
/// a `case` selecting only constants (a ROM, written with SMT arrays) and
/// empty modules (blackboxes, instances left undeclared). Each is compared
/// like any other; `queries` = number of controlled variables. (Yosys
/// 0.69 makes a ROM from 16 entries on, not from 8; 0.71 from 8 on.)
/// A design whose meaning depends on the macro `SYNTHESIS`; with it
/// defined as 1 (as by Yosys and v2rm), `y = a + 1`, and the debug code under
/// `` `ifndef SYNTHESIS `` (a string, which v2rm rejects) is not read.
const SYNTH: &str = "\
module synth (input logic [3:0] a, output logic [3:0] y);
`ifdef SYNTHESIS
  assign y = a + 4'(`SYNTHESIS);
`else
  assign y = ~a;
`endif
`ifndef SYNTHESIS
  logic [31:0] s;
  always_comb s = \"dbg\";
`endif
endmodule
";

#[test]
fn miter_yosys_defaults() {
    let Some((yosys, z3)) = tools() else { return };
    let labels: String = (0..15)
        .map(|i| format!("      4'd{i}: y = 3'd{};\n", (5 * i + 3) % 8))
        .collect();
    let rom = format!(
        "module rom (input logic [3:0] a, output logic [2:0] y);\n  always_comb\n    \
         case (a)\n{labels}      default: y = 3'd1;\n    endcase\nendmodule\n"
    );
    let cases = [
        ("rom", rom.as_str(), 1),
        (
            "holder",
            "\
module empty; endmodule
module holder (input logic clk, input logic [3:0] d, output logic [3:0] q);
  empty e();
  always_ff @(posedge clk) q <= d;
endmodule
",
            1,
        ),
        ("nothing", "module nothing (input logic a); endmodule\n", 0),
        // both sides read the code for synthesis (`SYNTHESIS` defined as 1)
        ("synth", SYNTH, 1),
    ];
    for (top, source, queries) in cases {
        let tmp = TempDir::new("yosys");
        let path = tmp.join(format!("{top}.sv"));
        std::fs::write(&path, source).unwrap();
        let inst = elab::load(source, &path).unwrap();
        let t = lower_inst(&inst).unwrap();
        let ys = yosys::run(&yosys, &[&path], top, &[]).unwrap();
        assert!(!ys.text.contains("Array"), "{top}: Yosys wrote a memory");
        let m = miter::build(&t, &ys).unwrap();
        let verdicts = miter::check(&z3, &m).unwrap();
        assert_eq!(
            verdicts.len(),
            2 * queries,
            "{top}: init and update queries"
        );
        for (phase, name, verdict) in verdicts {
            assert_eq!(verdict, Verdict::Equal, "{top}: `{name}` in {phase:?}");
        }
    }
}

/// A change to our round shows up as `Differs` on the variables it
/// affects, and only there.
#[test]
fn miter_differs() {
    let Some((yosys, z3)) = tools() else { return };
    let path = examples()
        .into_iter()
        .find(|p| p.ends_with("counter.sv"))
        .unwrap();
    let (_, _, mut m) = miter_of(&yosys, &path);
    // `q` counts down instead of up; `full` reads our `X(q)`
    let up = "(bvadd |*q| |%2|)";
    assert!(m.update.contains(up));
    m.update = m.update.replace(up, "(bvsub |*q| |%2|)");
    let verdicts = miter::check(&z3, &m).unwrap();
    let get = |p: Phase, n: &str| verdicts.iter().find(|q| q.0 == p && q.1 == n).unwrap().2;
    assert_eq!(get(Phase::Init, "q"), Verdict::Equal);
    assert_eq!(get(Phase::Init, "full"), Verdict::Equal);
    assert_eq!(get(Phase::Update, "q"), Verdict::Differs);
    assert_eq!(get(Phase::Update, "full"), Verdict::Differs);

    // `full` alone is wrong, in one round or the other: set when `q` is
    // all zeros
    let ones = "(= |X(q)| #b11111111)";
    for phase in [Phase::Init, Phase::Update] {
        let (_, _, mut m) = miter_of(&yosys, &path);
        let round = match phase {
            Phase::Init => &mut m.init,
            Phase::Update => &mut m.update,
        };
        assert!(round.contains(ones));
        *round = round.replace(ones, "(= |X(q)| #b00000000)");
        let verdicts = miter::check(&z3, &m).unwrap();
        let differs = |p| {
            if p == phase {
                Verdict::Differs
            } else {
                Verdict::Equal
            }
        };
        assert_eq!(
            verdicts,
            [
                (Phase::Init, "q".into(), Verdict::Equal),
                (Phase::Init, "full".into(), differs(Phase::Init)),
                (Phase::Update, "q".into(), Verdict::Equal),
                (Phase::Update, "full".into(), differs(Phase::Update)),
            ]
        );
    }
}

/// A variable missing on the Yosys side or of another width is an error,
/// and so is z3 output that is not one answer per query.
#[test]
fn miter_errors() {
    let Some((yosys, z3)) = tools() else { return };
    let path = examples()
        .into_iter()
        .find(|p| p.ends_with("counter.sv"))
        .unwrap();
    let (t, ys, m) = miter_of(&yosys, &path);
    let mut other = ys.clone();
    other.wires.remove("en");
    other.wires.insert("q".into(), 4);
    let e = miter::build(&t, &other).unwrap_err();
    assert!(e.contains("`en` is not a Yosys wire"), "{e}");
    assert!(e.contains("`q` has width 8, in Yosys 4"), "{e}");

    // under QF_BV, z3 rejects Yosys's declarations but still answers
    let mut bad = m.clone();
    bad.script = bad.script.replace("QF_UFBV", "QF_BV");
    let e = miter::check(&z3, &bad).unwrap_err();
    assert!(e.contains("unexpected z3 output"), "{e}");
}

/// The miter compares only our controlled variables and ties each of our
/// external variables to a Yosys wire, so a lowering bug that drops a signal
/// or turns a computed signal into a free one would leave nothing to find a
/// difference with. `build` therefore checks the interfaces: each stand-in
/// for such a bug (our translation of a changed text, Yosys's of the
/// original) is an error, not "all equal".
#[test]
fn miter_checks_interfaces() {
    let Some((yosys, z3)) = tools() else { return };
    let original = "\
module cnt (input logic clk, en, output logic [7:0] q, output logic full, output logic g);
  logic [7:0] n;
  logic f;
  assign n = q + 8'd1;
  always_ff @(posedge clk) if (en) q <= n;
  assign f = &q;
  assign full = f;
  assign g = full;
endmodule
";
    let tmp = TempDir::new("yosys");
    let path = tmp.join("interfaces.sv");
    std::fs::write(&path, original).unwrap();
    let ys = yosys::run(&yosys, &[&path], "cnt", &[]).unwrap();
    let ours = |source: &str| lower_inst(&elab::load(source, &path).unwrap()).unwrap();
    let m = miter::build(&ours(original), &ys).unwrap();
    let verdicts = miter::check(&z3, &m).unwrap();
    assert!(verdicts.iter().all(|(.., v)| *v == Verdict::Equal));

    let changed_all = |edits: &[(&str, &str)]| {
        let mut source = original.to_string();
        for (from, to) in edits {
            assert!(source.contains(from), "{from}");
            source = source.replace(from, to);
        }
        miter::build(&ours(&source), &ys).unwrap_err()
    };
    let changed = |from: &str, to: &str| changed_all(&[(from, to)]);
    let has = |e: &str, parts: &[&str]| {
        for part in parts {
            assert!(e.contains(part), "{part}\n{e}");
        }
    };
    // outputs dropped: nothing would compare them
    let e = changed(
        ", output logic full, output logic g);",
        ");\n  logic full, g;",
    );
    has(
        &e,
        &[
            "Yosys output `full` is not an output of ours",
            "Yosys output `g` is not an output of ours",
        ],
    );
    let e = changed_all(&[(", output logic g);", ");"), ("  assign g = full;\n", "")]);
    has(
        &e,
        &[
            "Yosys output `g` is not an output of ours",
            "Yosys wire `g` is no signal of ours",
        ],
    );
    let e = changed(
        "output logic full, output logic g);",
        "output logic full);\n  logic g;",
    );
    has(&e, &["Yosys output `g` is not an output of ours"]);
    // a computed output made an input: our free `full` would be tied to
    // Yosys's computed one, and `g` would compare equal
    let e = changed_all(&[
        (
            "output logic full, output logic g);",
            "input logic full, output logic g);",
        ),
        ("  assign full = f;\n", ""),
    ]);
    has(
        &e,
        &[
            "`full` is free in every round, in Yosys neither an input nor a blackbox output",
            "Yosys output `full` is not an output of ours",
        ],
    );
    // an internal signal dropped (inlined), or made the output of a
    // blackbox, which Yosys computes
    let e = changed_all(&[
        ("  logic [7:0] n;\n", ""),
        ("  assign n = q + 8'd1;\n", ""),
        ("q <= n;", "q <= q + 8'd1;"),
    ]);
    has(&e, &["Yosys wire `n` is no signal of ours"]);
    let e = changed_all(&[
        ("  assign f = &q;\n", "  src u (.o(f));\n"),
        (
            "endmodule\n",
            "endmodule\n(* blackbox *)\nmodule src (output logic o);\nendmodule\n",
        ),
    ]);
    has(
        &e,
        &["`f` is free in every round, in Yosys neither an input nor a blackbox output"],
    );
    // an output that Yosys does not have
    let e = changed(
        "output logic g);",
        "output logic g, output logic h);\n  assign h = g;",
    );
    has(&e, &["output `h` is not a Yosys output"]);
}

