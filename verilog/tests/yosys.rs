//! The Yosys helper: parsing `write_smt2` output, and the names and widths
//! Yosys gives the example designs against our translations. The tests that
//! run Yosys (and z3) are skipped with a message if it is not found.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use verilog::ast::{Const, Dir, Override, Ty};
use verilog::ast_interp::{Interp, Values};
use verilog::elab::{self, Inst};
use verilog::lower::{Translation, lower_inst};
use verilog::miter::{self, Side, Verdict};
use verilog::smt::Phase;
use verilog::{BitVec, typing, yosys, z3};

fn examples() -> Vec<PathBuf> {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("examples");
    let mut paths: Vec<PathBuf> = std::fs::read_dir(dir)
        .unwrap()
        .map(|e| e.unwrap().path())
        .filter(|p| p.extension().is_some_and(|e| e == "sv"))
        .collect();
    paths.sort();
    assert!(!paths.is_empty());
    paths
}

fn load(path: &Path) -> (Inst, Translation) {
    let inst = elab::load_file(path).unwrap_or_else(|e| panic!("{}:{e}", path.display()));
    let t = lower_inst(&inst).unwrap_or_else(|e| panic!("{}:{e}", path.display()));
    (inst, t)
}

/// The registers of a hierarchy by path, with their widths.
fn registers(inst: &Inst) -> BTreeMap<String, usize> {
    inst.registers()
        .into_iter()
        .map(|path| {
            let (prefix, q) = match path.rsplit_once('.') {
                Some((p, q)) => (format!("{p}."), q.to_string()),
                None => (String::new(), path.clone()),
            };
            let env = typing::env(&inst.at(&prefix).module).unwrap();
            let width = env[&q].ty.width;
            (path, width)
        })
        .collect()
}

/// The top ports in direction `dir`, with their widths.
fn ports(inst: &Inst, dir: Dir) -> BTreeMap<String, usize> {
    let ports = inst.module.ports.iter().filter(|p| p.dir == dir);
    ports
        .map(|p| (p.decl.name.clone(), p.decl.ty.width))
        .collect()
}

const SAMPLE: &str = "\
; SMT-LIBv2 description generated by Yosys
; yosys-smt2-module top
(declare-sort |top_s| 0)
; yosys-smt2-input a b 1
; yosys-smt2-wire a b 1
; yosys-smt2-clock a b posedge
; yosys-smt2-register u.q 8
; yosys-smt2-wire u.q 8
; yosys-smt2-output y 8
; yosys-smt2-wire y 8
; yosys-smt2-witness {\"type\": \"reg\"}
(define-fun |top_i| ((state |top_s|)) Bool (and
  (= (= ((_ extract 0 0) (|top#0| state)) #b1) true) ; $auto$clk2fflogic.cc:87:sample_control_edge$/clk#sampled$9
  (= (|top#1| state) #b00) ; $auto$clk2fflogic.cc:101:sample_data$/u.q#sampled$7
  (= (bvand (|top#2| state) #b00) #b00) ; $auto$clk2fflogic.cc:101:sample_data$/u.q#sampled$5
))
; yosys-smt2-topmod top
";

#[test]
fn parse_comments() {
    let s = yosys::parse(SAMPLE).unwrap();
    let map = |kv: &[(&str, usize)]| -> BTreeMap<String, usize> {
        kv.iter().map(|(k, w)| (k.to_string(), *w)).collect()
    };
    assert_eq!(s.top, "top");
    assert_eq!(s.text, SAMPLE);
    assert_eq!(s.inputs, map(&[("a b", 1)]));
    assert_eq!(s.outputs, map(&[("y", 8)]));
    assert_eq!(s.registers, map(&[("u.q", 8)]));
    assert_eq!(s.wires, map(&[("a b", 1), ("u.q", 8), ("y", 8)]));
    assert_eq!(s.state_sort(), "|top_s|");
    assert_eq!(s.transition("s", "t"), "(|top_t| s t)");
    assert_eq!(s.hierarchy("s"), "(|top_h| s)");
    assert_eq!(s.value("u.q", "s").unwrap(), "(|top_n u.q| s)");
    assert_eq!(
        s.value("a b", "s").unwrap(),
        "(ite (|top_n a b| s) #b1 #b0)"
    );
    assert_eq!(s.value("z", "s"), None);
    assert_eq!(s.initial("s"), "(|top_i| s)");
    assert_eq!(s.initial.len(), 3);
    let edge = "$auto$clk2fflogic.cc:87:sample_control_edge$/clk#sampled$9";
    let data = "$auto$clk2fflogic.cc:101:sample_data$/u.q#sampled$7";
    let output = "$auto$clk2fflogic.cc:101:sample_data$/u.q#sampled$5";
    assert!(!s.free_initially(edge));
    assert!(!s.free_initially(data));
    assert!(s.free_initially(output));
    assert!(s.free_initially("not mentioned"));
}

