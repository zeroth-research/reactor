//! The Yosys helper: parsing `write_smt2` output, and the names and widths
//! Yosys gives the example designs against our translations. The tests that
//! run Yosys (and z3) are skipped with a message if it is not found.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use verilog::ast::{Const, Dir, Override, Ty};
use verilog::elab::{self, Inst};
use verilog::lower::{Translation, lower_inst};
use verilog::miter::{self, Verdict};
use verilog::{BitVec, typing, yosys, z3};

fn examples() -> Vec<PathBuf> {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("examples");
    let mut paths: Vec<PathBuf> = std::fs::read_dir(dir)
        .unwrap()
        .map(|e| e.unwrap().path())
        .filter(|p| p.extension().is_some_and(|e| e == "sv"))
        .collect();
    paths.sort();
    assert!(!paths.is_empty());
    paths
}

fn load(path: &Path) -> (Inst, Translation) {
    let inst = elab::load_file(path).unwrap_or_else(|e| panic!("{}:{e}", path.display()));
    let t = lower_inst(&inst).unwrap_or_else(|e| panic!("{}:{e}", path.display()));
    (inst, t)
}

/// The registers of a hierarchy by path, with their widths.
fn registers(inst: &Inst) -> BTreeMap<String, usize> {
    inst.registers()
        .into_iter()
        .map(|path| {
            let (prefix, q) = match path.rsplit_once('.') {
                Some((p, q)) => (format!("{p}."), q.to_string()),
                None => (String::new(), path.clone()),
            };
            let env = typing::env(&inst.at(&prefix).module).unwrap();
            let width = env[&q].ty.width;
            (path, width)
        })
        .collect()
}

/// The top ports in direction `dir`, with their widths.
fn ports(inst: &Inst, dir: Dir) -> BTreeMap<String, usize> {
    let ports = inst.module.ports.iter().filter(|p| p.dir == dir);
    ports
        .map(|p| (p.decl.name.clone(), p.decl.ty.width))
        .collect()
}

const SAMPLE: &str = "\
; SMT-LIBv2 description generated by Yosys
; yosys-smt2-module top
(declare-sort |top_s| 0)
; yosys-smt2-input a b 1
; yosys-smt2-wire a b 1
; yosys-smt2-clock a b posedge
; yosys-smt2-register u.q 8
; yosys-smt2-wire u.q 8
; yosys-smt2-output y 8
; yosys-smt2-wire y 8
; yosys-smt2-witness {\"type\": \"reg\"}
; yosys-smt2-topmod top
";

#[test]
fn parse_comments() {
    let s = yosys::parse(SAMPLE).unwrap();
    let map = |kv: &[(&str, usize)]| -> BTreeMap<String, usize> {
        kv.iter().map(|(k, w)| (k.to_string(), *w)).collect()
    };
    assert_eq!(s.top, "top");
    assert_eq!(s.text, SAMPLE);
    assert_eq!(s.inputs, map(&[("a b", 1)]));
    assert_eq!(s.outputs, map(&[("y", 8)]));
    assert_eq!(s.registers, map(&[("u.q", 8)]));
    assert_eq!(s.wires, map(&[("a b", 1), ("u.q", 8), ("y", 8)]));
    assert_eq!(s.state_sort(), "|top_s|");
    assert_eq!(s.transition("s", "t"), "(|top_t| s t)");
    assert_eq!(s.hierarchy("s"), "(|top_h| s)");
    assert_eq!(s.value("u.q", "s").unwrap(), "(|top_n u.q| s)");
    assert_eq!(
        s.value("a b", "s").unwrap(),
        "(ite (|top_n a b| s) #b1 #b0)"
    );
    assert_eq!(s.value("z", "s"), None);
}

#[test]
fn parse_errors() {
    let err = |text: &str| yosys::parse(text).unwrap_err();
    let no_top = SAMPLE.replace("; yosys-smt2-topmod top\n", "");
    assert!(err(&no_top).contains("topmod"), "{}", err(&no_top));
    let two = format!("; yosys-smt2-module sub\n{SAMPLE}");
    assert!(
        err(&two).contains("expected only module `top`"),
        "{}",
        err(&two)
    );
    let widths = format!("{SAMPLE}; yosys-smt2-wire y 4\n");
    assert!(
        err(&widths).contains("`y` with widths 8 and 4"),
        "{}",
        err(&widths)
    );
    let malformed = format!("{SAMPLE}; yosys-smt2-wire y\n");
    assert!(err(&malformed).contains("malformed"), "{}", err(&malformed));
}

/// Overrides are rejected before Yosys is started.
#[test]
fn overrides_rejected() {
    let o = Override {
        name: "N".into(),
        value: Const {
            ty: Ty::INT,
            value: BitVec::new(32, 4u32).unwrap(),
        },
        span: Default::default(),
    };
    let e = yosys::run(Path::new("no-yosys"), Path::new("x.sv"), "top", &[o]).unwrap_err();
    assert!(e.contains("parameter overrides are not supported"), "{e}");
}

/// Yosys's registers are our register paths, its inputs and outputs are the
/// top ports (the clock and unread inputs included), and every variable of
/// our module except `q@init` is a Yosys wire of the same width. With z3,
/// every accessor of [`yosys::Smt2::value`] is a bit vector of the listed
/// width, and the transition and hierarchy predicates are satisfiable.
#[test]
fn names_match_examples() {
    let Some(bin) = yosys::find() else {
        eprintln!("yosys not found: skipped");
        return;
    };
    let z3 = z3::find();
    if z3.is_none() {
        eprintln!("z3 not found: accessor sorts not checked");
    }
    for path in examples() {
        let (inst, t) = load(&path);
        let ys = yosys::run(&bin, &path, &t.name, &[])
            .unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        let at = |what| format!("{}: {what}", path.display());
        assert_eq!(ys.top, t.name, "{}", at("top"));
        assert_eq!(ys.registers, registers(&inst), "{}", at("registers"));
        assert_eq!(ys.inputs, ports(&inst, Dir::Input), "{}", at("inputs"));
        assert_eq!(ys.outputs, ports(&inst, Dir::Output), "{}", at("outputs"));
        for (name, var) in &t.vars {
            if name.ends_with("@init") {
                continue;
            }
            let width = var.dtype().width();
            assert_eq!(ys.wires.get(name), Some(&width), "{}", at(name));
        }
        if let Some(z3) = &z3 {
            let mut script = ys.text.clone();
            script += &format!("(declare-const s {})\n", ys.state_sort());
            script += &format!("(declare-const t {})\n", ys.state_sort());
            script += &format!("(assert {})\n", ys.hierarchy("s"));
            script += &format!("(assert {})\n", ys.transition("s", "t"));
            for (i, (name, w)) in ys.wires.iter().enumerate() {
                let v = ys.value(name, "s").unwrap();
                script += &format!("(declare-const w{i} (_ BitVec {w}))\n(assert (= w{i} {v}))\n");
            }
            script += "(check-sat)\n";
            let out = z3::run(z3, &script).unwrap();
            assert_eq!(out, ["sat"], "{}", at("accessor sorts"));
        }
    }
}

/// Yosys and z3, or `None` (with a message) if one is missing.
fn tools() -> Option<(PathBuf, PathBuf)> {
    match (yosys::find(), z3::find()) {
        (Some(y), Some(z)) => Some((y, z)),
        _ => {
            eprintln!("yosys or z3 not found: skipped");
            None
        }
    }
}

/// The miter of an example, from Yosys's translation of it.
fn miter_of(yosys: &Path, path: &Path) -> (Translation, yosys::Smt2, miter::Miter) {
    let (_, t) = load(path);
    let ys =
        yosys::run(yosys, path, &t.name, &[]).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let m = miter::build(&t, &ys).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    (t, ys, m)
}

/// On every example, one round of our module and one transition of Yosys's
/// agree on every controlled variable, and every one is queried.
#[test]
fn miter_examples() {
    let Some((yosys, z3)) = tools() else { return };
    for path in examples() {
        let (t, _, m) = miter_of(&yosys, &path);
        let mut queried: Vec<&str> = m.queries.iter().map(|q| q.name.as_str()).collect();
        queried.sort();
        let mut controlled: Vec<&str> = t.module.ctrl().iter().map(|v| t.name(v)).collect();
        controlled.sort();
        assert_eq!(queried, controlled, "{}", path.display());
        for (name, verdict) in miter::check(&z3, &m).unwrap() {
            assert_eq!(verdict, Verdict::Equal, "{}: `{name}`", path.display());
        }
    }
}

/// A change to our round shows up as `Differs` on the variables it
/// affects, and only there.
#[test]
fn miter_differs() {
    let Some((yosys, z3)) = tools() else { return };
    let path = examples()
        .into_iter()
        .find(|p| p.ends_with("counter.sv"))
        .unwrap();
    let (_, _, mut m) = miter_of(&yosys, &path);
    // `q` counts down instead of up; `full` reads our `X(q)`
    let up = "(bvadd |*q| |%1|)";
    assert!(m.script.contains(up));
    m.script = m.script.replace(up, "(bvsub |*q| |%1|)");
    let verdicts = miter::check(&z3, &m).unwrap();
    let get = |n: &str| verdicts.iter().find(|(m, _)| m == n).unwrap().1;
    assert_eq!(get("q"), Verdict::Differs);
    assert_eq!(get("full"), Verdict::Differs);

    // `full` alone is wrong: set when `q` is all zeros
    let (_, _, mut m) = miter_of(&yosys, &path);
    let ones = "(= |X(q)| #b11111111)";
    assert!(m.script.contains(ones));
    m.script = m.script.replace(ones, "(= |X(q)| #b00000000)");
    let verdicts = miter::check(&z3, &m).unwrap();
    assert_eq!(
        verdicts,
        [
            ("q".into(), Verdict::Equal),
            ("full".into(), Verdict::Differs)
        ]
    );
}

/// A variable missing on the Yosys side or of another width is an error,
/// and so is z3 output that is not one answer per query.
#[test]
fn miter_errors() {
    let Some((yosys, z3)) = tools() else { return };
    let path = examples()
        .into_iter()
        .find(|p| p.ends_with("counter.sv"))
        .unwrap();
    let (t, ys, m) = miter_of(&yosys, &path);
    let mut other = ys.clone();
    other.wires.remove("en");
    other.wires.insert("q".into(), 4);
    let e = miter::build(&t, &other).unwrap_err();
    assert!(e.contains("`en` is not a Yosys wire"), "{e}");
    assert!(e.contains("`q` has width 8, in Yosys 4"), "{e}");

    // under QF_BV, z3 rejects Yosys's declarations but still answers
    let mut bad = m.clone();
    bad.script = bad.script.replace("QF_UFBV", "QF_BV");
    let e = miter::check(&z3, &bad).unwrap_err();
    assert!(e.contains("unexpected z3 output"), "{e}");
}

/// On every example, the registers of our translation are Yosys's, with
/// the same widths.
#[test]
fn registers_match_examples() {
    let Some(yosys) = yosys::find() else {
        eprintln!("yosys not found: skipped");
        return;
    };
    for path in examples() {
        let (inst, t) = load(&path);
        let ys = yosys::run(&yosys, &path, &t.name, &[])
            .unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        assert_eq!(
            miter::registers(&t, &ys),
            Vec::<String>::new(),
            "{}",
            path.display()
        );
        assert_eq!(ys.registers, registers(&inst), "{}", path.display());
    }
}

/// A register on one side only, or of another width, is named in the
/// error of `build`, next to the other mismatches; registers are compared
/// by path, also where the register's variable has another name.
#[test]
fn registers_mismatch() {
    let Some(yosys) = yosys::find() else {
        eprintln!("yosys not found: skipped");
        return;
    };
    let example = |name: &str| {
        let path = examples().into_iter().find(|p| p.ends_with(name)).unwrap();
        let (_, t) = load(&path);
        let ys = yosys::run(&yosys, &path, &t.name, &[]).unwrap();
        (t, ys)
    };

    // `nest`: register `m1.l.q` is the variable `m1.q`
    let (t, ys) = example("nest.sv");
    assert!(ys.registers.contains_key("m1.l.q"));
    assert!(!t.vars.contains_key("m1.l.q"));
    let mut other = ys.clone();
    other.registers.remove("m1.l.q");
    other.registers.insert("m2.l.q".into(), 3);
    other.registers.insert("m1.q".into(), 4);
    assert_eq!(
        miter::registers(&t, &other),
        [
            "register `m1.l.q` is not a Yosys register",
            "Yosys register `m1.q` is not one of ours",
            "register `m2.l.q` has width 4, in Yosys 3",
        ]
    );
    let e = miter::build(&t, &other).unwrap_err();
    assert!(
        e.contains("register `m1.l.q` is not a Yosys register"),
        "{e}"
    );

    // a register we lost: the miter would be unsound without the check,
    // since every name the round uses is still a Yosys wire
    let (mut t, ys) = example("counter.sv");
    t.registers.clear();
    assert_eq!(
        miter::registers(&t, &ys),
        ["Yosys register `q` is not one of ours"]
    );
    assert!(miter::build(&t, &ys).is_err());

    // register errors come first, wire errors are still reported
    let (t, mut ys) = example("counter.sv");
    ys.registers.insert("q".into(), 4);
    ys.wires.remove("en");
    let e = miter::build(&t, &ys).unwrap_err();
    assert_eq!(
        e,
        "the translations do not match: register `q` has width 8, in Yosys 4; \
         `en` is not a Yosys wire"
    );
}
