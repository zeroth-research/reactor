#!/bin/bash
# Coverage of the Lighthouse deck FPGA by v2rm: runs v2rm with each module of the generated
# LighthouseTopLevel.v as top, and on the hand-written ts4231Configurator.v alone, and with
# --yosys also the Yosys equivalence check (`v2rm --yosys`) of every accepted module.
# The files are used as generated, together with cells.v (blackbox stubs of the vendor cells).
#
# usage: measure.sh [--yosys] [DIR]   DIR = output of generate.sh (default ../sets/lighthouse)
# Writes ../results/lighthouse.tsv and ../results/lighthouse.md. V2RM overrides the v2rm binary
# (default ~/.cache/rm-target/release/v2rm). Acceptance runs one module after the other; the
# Yosys checks run in parallel (so their times depend on the load) and take hours: the two
# 128-entry FIFOs 15-25 min each, the whole top about two hours (almost all of it in z3).
set -uo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
YOSYS=0; [ "${1:-}" = --yosys ] && { YOSYS=1; shift; }
DIR=$(realpath "${1:-$HERE/../sets/lighthouse}")
V2RM=${V2RM:-$HOME/.cache/rm-target/release/v2rm}
export PATH="$HOME/tools/oss-cad-suite/bin:$PATH"
RES=$HERE/../results
"$HERE/generate.sh" --check "$DIR" || { echo "run $HERE/generate.sh first"; exit 1; }
[ -x "$V2RM" ] || { echo "$V2RM missing"; exit 1; }
DESIGN="$DIR/LighthouseTopLevel.v $DIR/ts4231Configurator.v $HERE/cells.v"
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
# Every v2rm runs under GNU `timeout`, which puts itself into a process group of its own and, when
# time is up or it gets SIGINT/SIGTERM, signals that whole group: v2rm and the z3 it runs.
# Interrupting this script passes the signal on to the `timeout`s of the background checks.
trap 'kill $(jobs -p) 2>/dev/null; wait; exit 130' INT TERM
QUERY_MS=3600000  # z3's time per query of `v2rm --yosys` (out of time: Unknown); the run's is 4 h

accept() {  # accept MODULE FILES...: v2rm result and seconds into $TMP/MODULE.v2rm
  local m=$1; shift
  local start=$(date +%s%N) s r
  timeout 60 "$V2RM" --top "$m" "$@" >/dev/null 2>"$TMP/$m.err"; s=$?
  local t=$(( ($(date +%s%N) - start) / 1000000 ))
  if [ $s = 124 ]; then r=TIMEOUT; elif [ $s = 0 ]; then r=OK
  else r=$(grep -v ': warning: ' "$TMP/$m.err" | head -1 | sed "s|$DIR/||; s|$HERE/||"); fi
  printf '%s\t%s\t%d.%03d' "$m" "$r" $((t / 1000)) $((t % 1000)) > "$TMP/$m.v2rm"
}

check() {  # check MODULE FILES...: Yosys result and seconds into $TMP/MODULE.yosys
  local m=$1; shift
  local start=$(date +%s) s ys
  timeout 14400 "$V2RM" --yosys -t:$QUERY_MS --top "$m" "$@" >"$TMP/$m.ys" 2>&1; s=$?
  if [ $s = 124 ]; then ys=TIMEOUT
  elif [ $s = 0 ]; then ys="Equal ($(grep -o '[0-9]* of [0-9]* queries' "$TMP/$m.ys"))"
  elif grep -q '^differs:' "$TMP/$m.ys"; then
    ys="Differs $(grep '^differs:' "$TMP/$m.ys" | cut -d'`' -f2 | tr '\n' ' ')"
  elif grep -q '^unknown:' "$TMP/$m.ys"; then
    ys="Unknown $(grep '^unknown:' "$TMP/$m.ys" | cut -d'`' -f2 | tr '\n' ' ')"
  else ys="Error $(grep -v ': warning: ' "$TMP/$m.ys" | tail -1 | sed "s|$DIR/||; s|$HERE/||")"; fi
  printf '\t%s\t%d' "$ys" $(( $(date +%s) - start )) > "$TMP/$m.yosys"
}

files() {  # the files read for MODULE
  if [ "$1" = ts4231Configurator ]; then echo "$DIR/ts4231Configurator.v"; else echo $DESIGN; fi
}

# acceptance one after the other (times comparable), Yosys checks in parallel
MODULES="$(sed -n 's/^module \([A-Za-z0-9_]*\).*/\1/p' "$DIR/LighthouseTopLevel.v") ts4231Configurator"
for m in $MODULES; do accept "$m" $(files "$m"); done
if [ $YOSYS = 1 ]; then
  for m in $MODULES; do
    [ "$(cut -f2 "$TMP/$m.v2rm")" = OK ] && check "$m" $(files "$m") &
  done
  wait
fi

{ printf 'module\tv2rm\tv2rm_s\tyosys\tyosys_s\n'
  for m in $MODULES; do
    cat "$TMP/$m.v2rm"; cat "$TMP/$m.yosys" 2>/dev/null || printf '\t-\t-'; echo
  done; } > "$RES/lighthouse.tsv"

n=$(( $(wc -l < "$RES/lighthouse.tsv") - 1 ))
ok=$(cut -f2 "$RES/lighthouse.tsv" | grep -cx OK)
eq=$(cut -f4 "$RES/lighthouse.tsv" | grep -c '^Equal')
v=$(git -C "$HERE" log -1 --format='%h %ci' | cut -c1-19)
lh=$(sed -n 's/^COMMIT=//p' "$HERE/generate.sh")
{ echo "# Lighthouse deck FPGA: coverage of v2rm"
  echo
  echo "Generated by \`lighthouse/measure.sh$([ $YOSYS = 1 ] && echo ' --yosys')\`; v2rm at commit \`$v\` of this repository,"
  echo "bitcraze/lighthouse-fpga at \`${lh:0:12}\`. One row per module as top (with its instances),"
  echo "files as generated plus the blackbox stubs \`cells.v\`; see \`lighthouse/README.md\`."
  echo
  echo "**$ok of $n** accepted$([ $YOSYS = 1 ] && echo ", **$eq** of them Yosys-equal")."
  echo
  echo "| module | v2rm | v2rm s | Yosys | Yosys s |"
  echo "|---|---|---:|---|---:|"
  tail -n +2 "$RES/lighthouse.tsv" | awk -F'\t' '{printf "| %s | %s | %s | %s | %s |\n", $1, $2, $3, $4, $5}'
} > "$RES/lighthouse.md"
cat "$RES/lighthouse.md"
